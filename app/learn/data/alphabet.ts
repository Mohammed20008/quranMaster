export function generateAlphabetLessons(rawLetters: RawAlphabetLetter[]): LessonData[] {
  return rawLetters.map((rl, index) => {
    // Generate custom unique 4-question quiz
    const idx = String(index + 1).padStart(2, '0');
    const quiz: QuizQuestion[] = [
      {
        id: `q_ar_${idx}_${rl.name.toLowerCase()}_1`,
        question: `What is the correct English name and pronunciation of "${rl.char}"?`,
        options: [rl.name, 'Seen', 'Jeem', 'Dal'],
        correctAnswer: 0,
        explanation: `The letter "${rl.char}" is named ${rl.name} in standard Arabic.`
      },
      {
        id: `q_ar_${idx}_${rl.name.toLowerCase()}_2`,
        question: `Which shape is the correct initial (beginning) form of "${rl.char}" when joining letters?`,
        options: [rl.initial, rl.isolated, rl.medial, rl.final],
        correctAnswer: 0,
        explanation: `The initial (start of a word) shape of "${rl.char}" is written as "${rl.initial}".`
      },
      {
        id: `q_ar_${idx}_${rl.name.toLowerCase()}_3`,
        question: `When the vowel Fathah (◌َ) is placed over "${rl.char}", what is the correct sound?`,
        options: [`"${rl.fathahSound}"`, `"${rl.kasrahSound}"`, `"${rl.dammahSound}"`, '"oon"'],
        correctAnswer: 0,
        explanation: `Fathah represents the short "a" sound, producing the pronunciation "${rl.fathahSound}" for "${rl.char}َ".`
      },
      {
        id: `q_ar_${idx}_${rl.name.toLowerCase()}_4`,
        question: `What is the English meaning of the vocabulary example "${rl.exampleArabic}" (${rl.exampleWord})?`,
        options: [rl.exampleTranslation, 'Book', 'Key', 'Water'],
        correctAnswer: 0,
        explanation: `The example word "${rl.exampleArabic}" (${rl.exampleWord}) translates to "${rl.exampleTranslation}".`
      }
    ];

    // Shuffle options and fix correct answer index
    const randomizedQuiz = quiz.map((q) => {
      const correctText = q.options[q.correctAnswer];
      const uniqueOptions = Array.from(new Set(q.options));
      while (uniqueOptions.length < 4) {
        uniqueOptions.push('Water', 'House', 'Mosque', 'Moon');
      }
      const shuffledOptions = [...uniqueOptions.slice(0, 4)].sort(() => Math.random() - 0.5);
      const newCorrectIndex = shuffledOptions.indexOf(correctText);
      return {
        ...q,
        options: shuffledOptions,
        correctAnswer: newCorrectIndex === -1 ? 0 : newCorrectIndex
      };
    });

    return {
      id: `ar_lsn_${String(index + 1).padStart(2, '0')}_${rl.name.toLowerCase()}`,
      title: `Letter Master: ${rl.name} (${rl.char})`,
      description: ``,
      points: 50,
      isAlphabet: true,
      alphabetData: {
        letters: [rl.char],
        letterDetails: {
          [rl.char]: {
            name: rl.name,
            shapes: {
              isNonConnecting: rl.isNonConnecting,
              isolated: rl.isolated,
              initial: rl.initial,
              medial: rl.medial,
              final: rl.final,
              exampleWord: rl.exampleWord,
              exampleTranslation: rl.exampleTranslation,
              exampleArabic: rl.exampleArabic,
              illustrationEmoji: rl.illustrationEmoji,
              letterExplanation: rl.explanation,
              isolatedWord: rl.exampleWord,
              isolatedTranslation: rl.exampleTranslation,
              isolatedArabic: rl.exampleArabic,
              isolatedEmoji: rl.illustrationEmoji,
              initialWord: rl.fathahWord,
              initialTranslation: rl.fathahTranslation,
              initialArabic: rl.fathahArabic,
              initialEmoji: rl.fathahEmoji,
              medialWord: rl.kasrahWord,
              medialTranslation: rl.kasrahTranslation,
              medialArabic: rl.kasrahArabic,
              medialEmoji: rl.kasrahEmoji,
              finalWord: rl.dammahWord,
              finalTranslation: rl.dammahTranslation,
              finalArabic: rl.dammahArabic,
              finalEmoji: rl.dammahEmoji
            },
            vowels: [
              {
                vowelName: 'Fathah',
                vowelMark: '◌َ',
                sound: rl.fathahSound,
                letterApplied: rl.char + 'َ',
                exampleWord: rl.fathahWord,
                exampleTranslation: rl.fathahTranslation,
                exampleArabic: rl.fathahArabic,
                illustrationEmoji: rl.fathahEmoji
              },
              {
                vowelName: 'Kasrah',
                vowelMark: '◌ِ',
                sound: rl.kasrahSound,
                letterApplied: rl.char + 'ِ',
                exampleWord: rl.kasrahWord,
                exampleTranslation: rl.kasrahTranslation,
                exampleArabic: rl.kasrahArabic,
                illustrationEmoji: rl.kasrahEmoji
              },
              {
                vowelName: 'Dammah',
                vowelMark: '◌ُ',
                sound: rl.dammahSound,
                letterApplied: rl.char + 'ُ',
                exampleWord: rl.dammahWord,
                exampleTranslation: rl.dammahTranslation,
                exampleArabic: rl.dammahArabic,
                illustrationEmoji: rl.dammahEmoji
              }
            ]
          }
        }
      },
      quiz: randomizedQuiz
    };
  });
}

export const alphabetLessons = generateAlphabetLessons(RAW_ALPHABET);
